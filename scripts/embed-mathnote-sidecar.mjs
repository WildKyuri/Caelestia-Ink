import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

// Embeds the sidecar source into the bundle so the plugin never executes a script from a
// path it discovered at runtime and never needs a writable temp file. The Python file stays
// the single source of truth; a test fails if the generated module drifts from it.
const root = path.resolve(import.meta.dirname, '..');
const sourcePath = path.join(root, 'integrations/mathnote/sidecar.py');
const targetPath = path.join(root, 'src/infrastructure/recognition/mathnote-sidecar-source.ts');

const source = readFileSync(sourcePath, 'utf8');
const output = [
  '// Generated by scripts/embed-mathnote-sidecar.mjs from integrations/mathnote/sidecar.py.',
  '// Do not edit by hand: run `npm run sidecar:embed` after editing the Python file.',
  `export const MATHNOTE_SIDECAR_SOURCE = ${JSON.stringify(source)};`,
  '',
].join('\n');

writeFileSync(targetPath, output);
console.log(`embedded ${source.length} bytes into ${path.relative(root, targetPath)}`);
